import matplotlib
matplotlib.use('macosx')
import numpy as np
import matplotlib.pyplot as plt
from astropy.timeseries import LombScargle

# Load and filter out bad photometry
raw_data = np.load('/Users/raynenkoonan/Desktop/Universtity/YEAR 4/STAR ANALYSIS MASTERS PROJECT/lc_3216432563376802688.npy')
clean_data = raw_data[(raw_data['flags'] == 0) & (raw_data['Combined_outliers'] == 0)]

# --- BYPASSING DATE SLICE TO GET FULL DATASET RESOLUTION ---
# Set your exact start and end Julian Dates
# start_date = 2460635.0
# end_date = 2460665.0
# date_mask = (clean_data['date'] >= start_date) & (clean_data['date'] <= end_date)
# dense_slice_data = clean_data[date_mask]

# Isolate a single band for the periodogram using the FULL dataset
mask_v = (clean_data['filter'] == 'I')

# Extract time, magnitude, and uncertainty for the full V-band
t = clean_data['date'][mask_v]
y = clean_data['calibrated_magnitude'][mask_v]
dy = clean_data['calibrated_error'][mask_v]

# Calculate the Lomb-Scargle periodogram
ls = LombScargle(t, y, dy)
frequency, power = ls.autopower(minimum_frequency=0.01, maximum_frequency=5.0)

# --- NEW: PRINTING THE RESOLUTION ---
print(f"\n==============================================")
print(f"AUTOGENERATED GRID RESOLUTION (FULL DATASET)")
print(f"Total test frequencies: {len(frequency)}")
print(f"Step size between tests: {frequency[1] - frequency[0]:.7f}")
print(f"==============================================\n")

# Identify the strongest periodic signal
best_frequency = frequency[np.argmax(power)]
best_period = 1.0 / best_frequency
print(f"Dominant Period (I-band): {best_period:.4f} days")

# Plot the Power Spectrum (Periodogram)
plt.figure(figsize=(10, 6))
plt.plot(1.0 / frequency, power, color='black', linewidth=1.0)

plt.xlabel('Period (days)')
plt.ylabel('Lomb-Scargle Power')
plt.title(f'I-Band Peiodogram (Full Dataset)\nPeak Period: {best_period:.4f} days | Resolution: {len(frequency)} points')

plt.xlim(0, 25)
plt.grid(True, linestyle='--', alpha=0.5)

plt.show()
